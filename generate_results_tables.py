from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict

import pandas as pd

PERIODS = [f"period_{i}" for i in range(1, 6)]


def as_float(value: Any, default: float = 0.0) -> float:
    """Safely convert values from JSON/CSV to float."""
    if value is None:
        return default
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def safe_div(num: float, den: float) -> float:
    """Return num/den, or 0.0 if denominator is zero."""
    return 0.0 if abs(den) < 1e-12 else num / den


def round2(x: float) -> float:
    return round(float(x), 2)


def read_cutting_plan(path: Path) -> Dict[str, Dict[str, Any]]:
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def read_retails_generated(data_root: Path, instance: str, period: str) -> dict[str, float]:
    """
    Retails generated by period_k are stored in data/<instance>/period_{k+1}/Retails.csv.
    For period_5, this reads period_6/Retails.csv.
    """
    k = int(period.split("_")[1])
    next_period = f"period_{k + 1}"
    retails_path = data_root / instance / next_period / "Retails.csv"

    if not retails_path.exists():
        return {
            "retails_generated_count": 0,
            "retails_generated_weight": 0.0,
            "retails_generated_avg_weight": 0.0,
        }

    df = pd.read_csv(retails_path)
    if df.empty:
        return {
            "retails_generated_count": 0,
            "retails_generated_weight": 0.0,
            "retails_generated_avg_weight": 0.0,
        }

    total_weight = as_float(df.get("Weight", pd.Series(dtype=float)).sum())
    count = int(len(df))
    return {
        "retails_generated_count": count,
        "retails_generated_weight": round2(total_weight),
        "retails_generated_avg_weight": round2(safe_div(total_weight, count)),
    }


def coil_record(instance: str, period: str, coil_id: str, coil: Dict[str, Any]) -> Dict[str, Any]:
    """Flatten one coil from cutting_plan.json into a row."""
    rolled = coil.get("rolled_leftover", {}) or {}
    lateral = coil.get("lateral_leftover", {}) or {}
    strips = coil.get("strips", []) or []

    return {
        "instance": instance,
        "period": period,
        "period_number": int(period.split("_")[1]),
        "coil_id": str(coil_id),
        "processed": int(coil.get("processed", 0)),
        "used": int(coil.get("used", 0)),
        "coil_width": as_float(coil.get("coil_width")),
        "coil_weight": as_float(coil.get("coil_weight")),
        "coil_ton_value": as_float(coil.get("coil_ton_value")),
        "used_length": as_float(coil.get("used_length")),
        "strip_count": len(strips),
        "strip_produced_weight": as_float(coil.get("---strip_produced_weight")),
        "strip_leftover_weight": as_float(coil.get("---strip_leftover_weight")),
        "strip_retail_weight": as_float(coil.get("------strip_retail_weight")),
        "strip_scrap_weight": as_float(coil.get("------strip_scrap_weight")),
        "strip_loss_weight": as_float(coil.get("---strip_loss_weight")),
        "lateral_leftover_weight": as_float(coil.get("---lateral_leftover_weight")),
        "lateral_leftover_retail_weight": as_float(lateral.get("---retail_weight")),
        "lateral_leftover_scrap_weight": as_float(lateral.get("---scrap_weight")),
        "edge_trim_weight": as_float(coil.get("---edge_trim_weight")),
        "rolled_leftover_weight": as_float(coil.get("---rolled_leftover_weight")),
        "rolled_leftover_width": as_float(rolled.get("width")),
        "rolled_leftover_length": as_float(rolled.get("length")),
        "processed_scrap_weight": as_float(coil.get("---processed_scrap_weight")),
    }


def aggregate_instance_period(
        instance: str,
        period: str,
        coils_df: pd.DataFrame,
        retails_info: Dict[str, float],
) -> Dict[str, Any]:
    """Build the main summary row for one instance-period."""
    new_df = coils_df[(coils_df["processed"] == 0) & (coils_df["used"] == 1)]
    proc_df = coils_df[coils_df["processed"] == 1]

    new_coil_weight = new_df["coil_weight"].sum()
    proc_coil_weight = proc_df["coil_weight"].sum()
    total_produced = new_df["strip_produced_weight"].sum() + proc_df["strip_produced_weight"].sum()

    row = {
        "instance": instance,
        "period": period,
        "period_number": int(period.split("_")[1]),

        # New coils: Processed = 0 and used in the plan.
        "new_coils_used_count": int(len(new_df)),
        "new_coils_weight": round2(new_coil_weight),
        "new_strip_produced_weight": round2(new_df["strip_produced_weight"].sum()),
        "new_strip_retail_weight": round2(new_df["strip_retail_weight"].sum()),
        "new_strip_scrap_weight": round2(new_df["strip_scrap_weight"].sum()),
        "new_strip_loss_weight": round2(new_df["strip_loss_weight"].sum()),
        "new_lateral_leftover_weight": round2(new_df["lateral_leftover_weight"].sum()),
        "new_edge_trim_weight": round2(new_df["edge_trim_weight"].sum()),
        "new_rolled_leftover_weight": round2(new_df["rolled_leftover_weight"].sum()),
        "new_partially_used_count": int((new_df["rolled_leftover_weight"] > 0.0).sum()),

        # Processed coils: Processed = 1, including used and unused previous-period retails.
        "processed_coils_total_count": int(len(proc_df)),
        "processed_coils_used_count": int((proc_df["used"] == 1).sum()),
        "processed_coils_weight": round2(proc_coil_weight),
        "processed_strip_produced_weight": round2(proc_df["strip_produced_weight"].sum()),
        "processed_scrap_weight": round2(proc_df["processed_scrap_weight"].sum()),

        # Overall production dependency on processed retails.
        "total_strip_produced_weight": round2(total_produced),

        # Retails generated for the next period.
        **retails_info,
    }

    return row


def aggregate_instance_period_value(
        instance: str,
        period: str,
        coils_df: pd.DataFrame
) -> Dict[str, Any]:
    df = coils_df.copy()

    weight_columns = [
        "coil_weight",
        "strip_produced_weight",
        "strip_retail_weight",
        "strip_scrap_weight",
        "strip_loss_weight",
        "lateral_leftover_weight",
        "edge_trim_weight",
        "rolled_leftover_weight",
        "processed_scrap_weight",
    ]

    for col in weight_columns:
        df[f"{col}_value"] = (
                df[col] / 1000.0 * df["coil_ton_value"]
        )

    new_df = df[(df["processed"] == 0) & (df["used"] == 1)]
    proc_df = df[df["processed"] == 1]

    row = {
        "instance": instance,
        "period": period,
        "period_number": int(period.split("_")[1]),

        # Bobinas novas
        "new_coils_used_count": int(len(new_df)),
        "new_coils_value": round2(new_df["coil_weight_value"].sum()),
        "new_strip_produced_value": round2(new_df["strip_produced_weight_value"].sum()),
        "new_strip_retail_value": round2(new_df["strip_retail_weight_value"].sum()),
        "new_strip_scrap_value": round2(new_df["strip_scrap_weight_value"].sum()),
        "new_strip_loss_value": round2(new_df["strip_loss_weight_value"].sum()),
        "new_lateral_leftover_value": round2(new_df["lateral_leftover_weight_value"].sum()),
        "new_edge_trim_value": round2(new_df["edge_trim_weight_value"].sum()),
        "new_rolled_leftover_value": round2(new_df["rolled_leftover_weight_value"].sum()),

        # Bobinas processadas
        "processed_coils_total_count": int(len(proc_df)),
        "processed_coils_used_count": int((proc_df["used"] == 1).sum()),
        "processed_coils_value": round2(proc_df["coil_weight_value"].sum()),
        "processed_strip_produced_value": round2(proc_df["strip_produced_weight_value"].sum()),
        "processed_scrap_value": round2(proc_df["processed_scrap_weight_value"].sum()),
    }

    return row


def build_tables(results_root: Path) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    data_root = results_root / "data"
    output_root = results_root / "output"

    coil_rows = []
    summary_rows = []
    summary_value_rows = []

    instances = sorted([p.name for p in output_root.iterdir() if p.is_dir()])

    for instance in instances:
        for period in PERIODS:
            plan_path = output_root / instance / period / "cutting_plan.json"
            if not plan_path.exists():
                continue

            cutting_plan = read_cutting_plan(plan_path)
            period_coil_rows = [
                coil_record(instance, period, coil_id, coil)
                for coil_id, coil in cutting_plan.items()
            ]
            period_coils_df = pd.DataFrame(period_coil_rows)

            if period_coils_df.empty:
                continue

            retails_info = read_retails_generated(data_root, instance, period)
            summary_row = aggregate_instance_period(instance, period, period_coils_df, retails_info)

            summary_value_row = aggregate_instance_period_value(instance, period, period_coils_df)

            coil_rows.extend(period_coil_rows)
            summary_rows.append(summary_row)
            summary_value_rows.append(summary_value_row)

    coil_level_df = pd.DataFrame(coil_rows).sort_values(["instance", "period_number", "processed", "coil_id"])
    summary_df = pd.DataFrame(summary_rows).sort_values(["instance", "period_number"])
    summary_value_df = pd.DataFrame(summary_value_rows).sort_values(["instance", "period_number"])

    # Derived analytical rates.
    rates_rows = []
    for row in summary_df.to_dict(orient="records"):
        new_weight = as_float(row["new_coils_weight"])
        proc_weight = as_float(row["processed_coils_weight"])
        total_prod = as_float(row["total_strip_produced_weight"])

        new_reusable = (
                as_float(row["new_strip_retail_weight"])
                + as_float(row["new_lateral_leftover_weight"])
                + as_float(row["new_rolled_leftover_weight"])
        )
        new_scrap_like = (
                as_float(row["new_strip_scrap_weight"])
                + as_float(row["new_strip_loss_weight"])
                + as_float(row["new_edge_trim_weight"])
        )

        rates_rows.append({
            "instance": row["instance"],
            "period": row["period"],
            "period_number": row["period_number"],
            "new_production_rate": round2(100.0 * safe_div(as_float(row["new_strip_produced_weight"]), new_weight)),
            "new_reusable_rate": round2(100.0 * safe_div(new_reusable, new_weight)),
            "new_scrap_rate": round2(100.0 * safe_div(new_scrap_like, new_weight)),
            "processed_recovery_rate": round2(
                100.0 * safe_div(as_float(row["processed_strip_produced_weight"]), proc_weight)),
            "processed_discard_rate": round2(100.0 * safe_div(as_float(row["processed_scrap_weight"]), proc_weight)),
            "reuse_dependency_rate": round2(
                100.0 * safe_div(as_float(row["processed_strip_produced_weight"]), total_prod)),
        })

    rates_df = pd.DataFrame(rates_rows).sort_values(["instance", "period_number"])

    return summary_df, summary_value_df, rates_df, coil_level_df


def write_outputs(
        summary_df: pd.DataFrame,
        summary_value_df: pd.DataFrame,
        rates_df: pd.DataFrame,
        coil_level_df: pd.DataFrame,
        output_dir: Path,
) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)

    summary_df.to_csv(output_dir / "summary_by_instance_period.csv", index=False)
    summary_value_df.to_csv(output_dir / "summary_value_by_instance_period.csv", index=False)
    rates_df.to_csv(output_dir / "rates_by_instance_period.csv", index=False)
    coil_level_df.to_csv(output_dir / "coil_level_summary.csv", index=False)


def main() -> None:
    project_root = Path.cwd()

    if not (project_root / "data").is_dir():
        raise FileNotFoundError(f"Pasta data/ não encontrada em: {project_root}")

    if not (project_root / "output").is_dir():
        raise FileNotFoundError(f"Pasta output/ não encontrada em: {project_root}")

    results_root = project_root
    output_dir = project_root / "results"

    summary_df, summary_value_df, rates_df, coil_level_df = build_tables(results_root)

    write_outputs(
        summary_df=summary_df,
        summary_value_df=summary_value_df,
        rates_df=rates_df,
        coil_level_df=coil_level_df,
        output_dir=output_dir,
    )

    print(f"Project root: {project_root}")
    print(f"Output directory: {output_dir}")
    print(
        f"Rows: summary={len(summary_df)}, "
        f"summary_value={len(summary_value_df)}, "
        f"rates={len(rates_df)}, "
        f"coil_level={len(coil_level_df)}"
    )


if __name__ == "__main__":
    main()
